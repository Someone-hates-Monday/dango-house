for (const [locale, map] of Object.entries(packs)) {
  const file = `src/shared/i18n/${files[locale]}`;
  let s = fs.readFileSync(file, 'utf8');
  if (s.includes("'settings.pairTone'")) {
    console.log('skip', file);
    continue;
  }
  const extra = Object.entries(map)
    .map(([k, v]) => `  '${k}': ${JSON.stringify(v)},`)
    .join('\n');
  s = s.replace(/\n\};\s*$/, `\n\n${extra}\n};\n`);
  fs.writeFileSync(file, s);
  console.log('patched', file);
}
