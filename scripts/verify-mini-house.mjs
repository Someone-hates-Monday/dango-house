import {_electron as electron} from 'playwright';
import path from 'node:path';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {waitHouseState} from './house-test-helpers.mjs';

const out=path.resolve('test-results/mini-house');fs.mkdirSync(out,{recursive:true});
const profile=path.join(out,'profile-'+Date.now()),env={...process.env,GARDEN_TEST_DATA:profile,GARDEN_TEST_HOUSE:'1'};
delete env.ELECTRON_RUN_AS_NODE;
const packaged=process.argv.includes('--packaged'),version=JSON.parse(fs.readFileSync('package.json','utf8')).version;
const options={...(packaged?{executablePath:path.resolve(`release/v${version}/win-unpacked/团子小屋.exe`)}:{}),args:packaged?[`--user-data-dir=${profile}`]:[process.cwd()],env};
let app=await electron.launch(options);
const errors=[];
const findHouse=async()=>{await app.firstWindow();for(let i=0;i<100;i++){const p=app.windows().find(p=>p.url().includes('view=house'));if(p){p.on('pageerror',e=>errors.push(e.message));await p.locator('.mini-frame').waitFor();return p;}await new Promise(r=>setTimeout(r,100));}throw Error('No mini house');};
try{
 let house=await findHouse();
 const send=a=>house.evaluate(a=>window.garden.dispatch(a),a);
 await send({type:'settings',patch:{autonomous:false}});
 await send({type:'room-settings',patch:{autonomous:false,wandering:false}});
 assert.equal(await house.locator('svg.house-shell').count(),1);
 await house.waitForTimeout(500);
 await house.screenshot({path:path.join(out,'compact.png'),omitBackground:true,scale:'css'});
 const buttons=await house.locator('.house-header button').evaluateAll(els=>els.map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height,topmost:document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)?.closest('button')===e};}));
 assert.ok(buttons.every(b=>b.w>=32&&b.h>=32&&b.topmost),'roof buttons must be visible and clickable');
 for(let i=1;i<buttons.length;i++)assert.ok(buttons[i].x>=buttons[i-1].x+buttons[i-1].w,'roof controls must not overlap');
 await house.getByRole('button',{name:'设置与连接',exact:true}).click();
 const main=app.windows().find(p=>/view=(chat|settings)/.test(p.url()));
 await main.locator('.connections-page').waitFor();
 assert.equal(await main.locator('.member-list').count(),0,'global settings must not imply a selected resident');
 await main.getByRole('button',{name:'AI 连接',exact:true}).click();
 await main.waitForTimeout(300);await main.screenshot({path:path.join(out,'connection.png'),scale:'css'});
 await main.getByRole('button',{name:'高级选项',exact:true}).click();
 assert.ok(await main.getByRole('button',{name:'进入桌宠 / Dock 模式',exact:true}).isVisible());
 await main.locator('.back-house-control').click();
 const pin=house.getByRole('button',{name:'切换置顶',exact:true});
 assert.equal(await pin.getAttribute('aria-pressed'),'true');await pin.click();
 await house.waitForFunction(()=>document.querySelector('.house-pin').getAttribute('aria-pressed')==='false');
 const pinnedNative=await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('view=house')).isAlwaysOnTop());
 assert.equal(pinnedNative,false);
 assert.ok(!(await pin.getAttribute('class')).includes('is-pinned'));
 await house.getByRole('button',{name:'聊聊',exact:true}).click();
 await house.locator('.house-chat textarea').fill('大家今天想做什么？');
 await house.getByRole('button',{name:'发送',exact:true}).click();
 await waitHouseState(house,s=>!s.busy);
 await house.getByRole('button',{name:'Claude',exact:true}).click();
 await house.locator('.house-speech').waitFor();
 await house.waitForFunction(()=>document.querySelector('.house-chat header strong')?.textContent?.includes('Claude'));
 await house.screenshot({path:path.join(out,'private.png'),omitBackground:true,scale:'css'});
 await house.getByRole('button',{name:'小屋群聊',exact:true}).click();
 await house.getByRole('button',{name:'关闭聊天',exact:true}).click();
 await send({type:'cast-preset',preset:'all'});
 await house.waitForFunction(()=>document.querySelectorAll('.house-resident').length===7&&Number(document.querySelector('.house-root').dataset.houseRoomHeight)>=370);
 assert.equal(await house.locator('.house-resident').count(),7);
 await house.waitForFunction(()=>[...document.querySelectorAll('.house-resident .cast-idle-video')].every(v=>!v.src||v.readyState>=2));
 await house.screenshot({path:path.join(out,'seven-residents.png'),omitBackground:true,scale:'css'});
 await send({type:'cast-preset',preset:'core'});
 await send({type:'stop'});
 // Resize and give the single shared CG sufficient headroom.
 await house.evaluate(()=>window.garden.houseLayout({width:460,height:300,chatOpen:false,cgHeight:0}));
 await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('view=house'));const b=w.getBounds();w.setPosition(b.x,350);});
 await send({type:'cg-preview',host:'room',asset:'rin-xia-cheek-t1'});
 await house.waitForSelector('.house-cg video',{timeout:30000});
 await house.waitForFunction(()=>{const v=document.querySelector('.house-cg video');return v.readyState>=2&&v.currentTime>.1;});
 assert.equal(await house.locator('.house-cg').count(),1);
 assert.equal(await main.locator('.cg-moment').count(),0);
 await house.screenshot({path:path.join(out,'roof-cg.png'),omitBackground:true,scale:'css'});
 await waitHouseState(house,s=>!s.cgSession&&s.cgLastReceipt?.outcome==='ended',15000);
 const size=await house.evaluate(()=>window.garden.houseLayout());
 await app.close();app=await electron.launch(options);house=await findHouse();
 const restored=await house.evaluate(()=>window.garden.houseLayout());
 assert.equal(restored.pinned,false);assert.equal(restored.width,size.width);assert.equal(restored.height,size.height);
 assert.deepEqual(errors,[]);
 const report={success:true,packaged,roofControlsClickable:true,globalSettings:true,pinNativeAndPersisted:true,speechBubbles:true,oneSharedCg:true,sevenResidents:true,persistedSize:true,size:restored,errors};
 fs.writeFileSync(path.join(out,'verification.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report));
}finally{await app.close();}
