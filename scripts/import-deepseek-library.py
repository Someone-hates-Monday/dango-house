"""Import upstream transparent clips at a pinned commit, with Git/SHA256 verification."""
import json, hashlib, urllib.request, concurrent.futures, pathlib, subprocess, re
import imageio_ffmpeg
root=pathlib.Path(__file__).resolve().parent.parent
tree=json.loads((root/'test-results/deepseek-upstream-20261104.json').read_text(encoding='utf-8-sig'))
folder=root/'public/video/deepseek'
manifest=json.loads((folder/'manifest.json').read_text(encoding='utf-8-sig'))
old={r['gitBlob']:r for r in manifest['records']}
def load(item):
    previous=old.get(item['sha'])
    name=previous['name'] if previous else 'extra-'+item['sha'][:12]
    dest=folder/(name+'.webm')
    url='https://raw.githubusercontent.com/PC2005-cloud/dsh-pet/'+tree['sha']+'/'+urllib.parse.quote(item['path'])
    if dest.exists(): data=dest.read_bytes()
    else:
        for attempt in range(3):
            try:
                opener=urllib.request.build_opener(urllib.request.ProxyHandler({'https':'http://localhost:15236'}))
                data=opener.open(url,timeout=35).read(); break
            except Exception:
                if attempt==2: raise
    assert hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()==item['sha']
    dest.write_bytes(data)
    title=pathlib.PurePosixPath(item['path']).stem
    group='food' if any(s in title for s in ['吃','午餐','火锅','零食','糖葫芦']) else 'seasonal' if any(s in title for s in ['中秋','重阳','圣诞','春节','红包','福字','月饼','粽子','茱萸','孔明','河灯','烟花','乞巧','南瓜','雪人']) else 'rest' if any(s in title for s in ['睡','小憩','哈欠','伸懒腰','瞌睡']) else 'emotion' if any(s in title for s in ['回应','生气','惊','叹气','尾巴拍','礼仪']) else 'work' if any(s in title for s in ['工作','代码','思考','记录','清点','余额','碎碎念']) else 'play'
    probe=subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(),'-i',str(dest)],capture_output=True).stderr.decode(errors='replace')
    match=re.search(r'Duration: (\d+):(\d+):(\d+\.\d+)',probe)
    seconds=round(int(match[1])*3600+int(match[2])*60+float(match[3]),3) if match else 10
    assert seconds>0 and 'Video:' in probe, title
    return {'name':name,'title':title,'group':group,'seconds':seconds,'path':name+'.webm','source':url,'gitBlob':item['sha'],'sha256':hashlib.sha256(data).hexdigest()}
with concurrent.futures.ThreadPoolExecutor(max_workers=5) as pool: records=list(pool.map(load,tree['clips']))
manifest.update(commit=tree['sha'],records=records)
(folder/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
catalog=[{'id':r['name'],'title':r['title'],'group':r['group'],'seconds':r['seconds'],'src':'./video/deepseek/'+r['path']} for r in records]
(root/'src/shared/deepseek-clips.ts').write_text('// Generated by scripts/import-deepseek-library.py; upstream terms remain in public/video/deepseek.\nexport const deepseekClips = '+json.dumps(catalog,ensure_ascii=False,indent=2)+' as const;\n',encoding='utf-8')
print(f'Imported and verified {len(records)} clips at {tree["sha"]}')
